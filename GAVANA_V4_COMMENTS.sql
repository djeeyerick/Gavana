-- Run this once in Supabase SQL Editor.
create table if not exists public.movie_comments (
  id bigint generated by default as identity primary key,
  movie_id text not null,
  name text not null check (char_length(trim(name)) between 1 and 80),
  email text not null check (char_length(trim(email)) between 3 and 254),
  comment text not null check (char_length(trim(comment)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists movie_comments_movie_created_idx
  on public.movie_comments (movie_id, created_at desc);
alter table public.movie_comments enable row level security;
drop policy if exists "Public can read movie comments" on public.movie_comments;
create policy "Public can read movie comments"
  on public.movie_comments for select to anon, authenticated using (true);
drop policy if exists "Visitors can post movie comments" on public.movie_comments;
create policy "Visitors can post movie comments"
  on public.movie_comments for insert to anon, authenticated
  with check (
    char_length(trim(name)) between 1 and 80
    and char_length(trim(email)) between 3 and 254
    and char_length(trim(comment)) between 1 and 2000
  );
grant select, insert on public.movie_comments to anon, authenticated;
grant usage, select on sequence public.movie_comments_id_seq to anon, authenticated;
