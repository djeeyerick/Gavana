-- GAVANA FILMS: allow Watch and Download links to be added separately.
-- Run this once in Supabase SQL Editor. It only drops NOT NULL on the optional link columns.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='movie_parts' and column_name='watch_url') then
    execute 'alter table public.movie_parts alter column watch_url drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='movie_parts' and column_name='download_url') then
    execute 'alter table public.movie_parts alter column download_url drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='episodes' and column_name='video_url') then
    execute 'alter table public.episodes alter column video_url drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='episodes' and column_name='download_url') then
    execute 'alter table public.episodes alter column download_url drop not null';
  end if;
end $$;

-- Anonymous content view counts (movie/series ID only; no visitor identity is stored).
create table if not exists public.movie_views (
  id bigint generated by default as identity primary key,
  movie_id text not null,
  created_at timestamptz not null default now()
);
create index if not exists movie_views_created_at_idx on public.movie_views(created_at desc);
alter table public.movie_views enable row level security;
drop policy if exists "Public can record content views" on public.movie_views;
create policy "Public can record content views" on public.movie_views for insert to anon, authenticated with check (true);
drop policy if exists "Public can read content views" on public.movie_views;
create policy "Public can read content views" on public.movie_views for select to anon, authenticated using (true);
